import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const read=name=>readFile(new URL('../fit74/'+name,import.meta.url),'utf8');
const win={};
for(const name of ['rhythm-core.js','recovery-core.js']) vm.runInNewContext(await read(name),{window:win,Date,Math,Map,Set,Object,Number});
const c=win.Fit74RhythmCore,r=win.Fit74RecoveryCore;
const good=d=>({entry_date:d,workout:true,nutrition:2,movement:true});
const base={start:'2026-11-01',end:'2026-12-31',today:'2026-11-24',entries:[good('2026-11-19')]};
assert(c.state(base).suggestion);
assert(!c.state({...base,entries:[]}).suggestion);
assert.equal(c.state({...base,entries:[good('2026-11-23')]}).gap,0);
assert.equal(c.state({...base,rows:['20','21','22','23'].map(d=>({entry_date:'2026-11-'+d,paused:true}))}).gap,0);
assert.equal(c.state({...base,shift:{kind:'recovery',code:'REST'},rows:[{entry_date:base.today,energy:'high'}]}).mode,'rest');
assert.equal(c.state({...base,rows:[{entry_date:base.today,energy:'high',restart_stage:1}]}).mode,'rest');
assert.equal(c.state({...base,rows:[{entry_date:'2026-11-23',restart_stage:2}]}).mode,'light');
assert.equal(c.state({...base,rows:[{entry_date:'2026-11-23',restart_stage:3}]}).mode,'regular');
assert(!c.state({...base,rows:[{entry_date:base.today,restart_stage:0}]}).suggestion);
assert.equal(c.state({...base,rows:[{entry_date:base.today,paused:true},{entry_date:'2026-11-25',paused:true}]}).until,'2026-11-25');
const p=r.calculate({start:'2026-11-20',end:'2026-12-31',today:'2026-11-24',entries:[good('2026-11-20'),good('2026-11-23')],pausedDates:['2026-11-21','2026-11-22']});
assert.equal(p.fortnight.total,2);assert.equal(p.fortnight.completed,2);assert.equal(p.returns,0);assert(!p.show);
const rows=[{entry_date:base.today,energy:'low',micro_checkin:true}];
assert(c.earn({state:c.state({...base,rows}),rows,entries:base.entries,stable:r.stable}).includes('balance'));
assert.equal(r.score(rows[0]),0);
assert(c.earn({state:c.state(base),entries:base.entries,stable:r.stable,contexts:[{reason:'fatigue'}]}).includes('honest'));
const html=await read('index.html');
assert(html.indexOf('rhythm-ui.js')<html.indexOf('v3.js'));
for(const id of ['rhythmCard','rhythmStart','rhythmCheckin','rhythmAwards','rhythmResume','rhythmStageName','rhythmShowFull'])assert(html.includes('id="'+id+'"'));
new vm.Script(await read('rhythm-ui.js'));new vm.Script(await read('v3.js'));
console.log('Fit74 2.0: restart, shift constraints, pause metrics, awards and UI contracts passed');
